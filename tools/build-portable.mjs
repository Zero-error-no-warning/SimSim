import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {build,version as esbuildVersion} from 'esbuild';
import {UI_BUILD} from '../src/ui-dom.js?v=20261009-information-analysis-26';

const root=fileURLToPath(new URL('..',import.meta.url)),out=path.join(root,'portable');
const inputFiles=['index.html','styles.css','tools/build-portable.mjs','tools/portable-copy.html',...['src','data','vendor/three'].flatMap(dir=>fs.readdirSync(path.join(root,dir)).sort().map(name=>dir+'/'+name))];
const hash=createHash('sha256').update(esbuildVersion);
for(const name of inputFiles)hash.update(name+'\0').update(fs.readFileSync(path.join(root,name)));
const buildId=UI_BUILD+'-'+hash.digest('hex').slice(0,12);
const samples=Object.fromEntries(fs.readdirSync(path.join(root,'data')).filter(name=>name.endsWith('.txt')).sort().map(name=>{
  const text=fs.readFileSync(path.join(root,'data',name),'utf8');return [name,JSON.stringify(JSON.parse(text))];
}));
const runtime=`export const base=new URL('.',document.currentScript.src);
const samples=${JSON.stringify(samples)};
export function sampleResponse(name){
  if(!Object.hasOwn(samples,name))throw new Error('サンプルが見つかりません: '+name);
  return {ok:true,status:200,json:async()=>JSON.parse(samples[name])};
}`;
function replaceOnce(source,pattern,replacement,label){
  let count=0;
  const result=source.replace(pattern,(...args)=>{count++;return typeof replacement==='function'?replacement(...args):replacement;});
  if(count!==1)throw new Error(label+': expected one match, found '+count);
  return result;
}
const plugin={name:'portable',setup(builder){
  builder.onResolve({filter:/^portable:runtime$/},()=>({path:'runtime',namespace:'portable'}));
  builder.onLoad({filter:/.*/,namespace:'portable'},()=>({contents:runtime,loader:'js'}));
  builder.onResolve({filter:/\.js\?v=/},args=>({path:path.resolve(args.resolveDir,args.path.split('?')[0])}));
  builder.onLoad({filter:/[\\/]src[\\/](app|analysis-ui|bootstrap)\.js$/},args=>{
    let source=fs.readFileSync(args.path,'utf8');
    if(path.basename(args.path)==='bootstrap.js'){
      source=replaceOnce(source,/document\.querySelector\('script\[src\*="bootstrap\.js"\]'\)/,"document.querySelector('script[src*=\"main.js\"]')",'bootstrap report');
      source=replaceOnce(source,/(import\('\.\/app\.js\?v=[^']+'\))\.catch/,(_,entry)=>entry+'.then(module=>module.portableReady).catch','startup promise');
    }else{
      const worker=path.basename(args.path)==='app.js'?'worker.js':'analysis-worker.js';
      source="import {base as portableBase,sampleResponse} from 'portable:runtime';\n"+source;
      source=replaceOnce(source,/new URL\('\.\/(?:analysis-)?worker\.js\?v=[^']+',import\.meta\.url\)/,`new URL('${worker}?v=${buildId}',portableBase)`,'worker URL');
      source=replaceOnce(source,/type:'module',/,'','classic worker');
      if(worker==='worker.js'){
        source=replaceOnce(source,/fetch\(new URL\('\.\.\/data\/'\+file,import\.meta\.url\),\{\s*signal:controller\.signal\s*\}\)/,'Promise.resolve(sampleResponse(file))','bundled sample');
        source=replaceOnce(source,/await Promise\.all\(\[worker\.ready,analysisUI\.worker\.ready\]\)\.then\(\(\)=>loadDemo\(true\)\);\s*requestAnimationFrame\(frame\);/,'export const portableReady=Promise.all([worker.ready,analysisUI.worker.ready]).then(()=>loadDemo(true)).then(()=>requestAnimationFrame(frame));','initial sample promise');
      }
    }
    return {contents:source,loader:'js',resolveDir:path.dirname(args.path)};
  });
}};

fs.mkdirSync(out,{recursive:true});
const license=fs.readFileSync(path.join(root,'vendor/three/LICENSE.txt'),'utf8');
for(const [name,entry] of [['main.js','main'],['worker.js','src/worker.js'],['analysis-worker.js','src/analysis-worker.js']]){
  const result=await build({absWorkingDir:root,define:{SIMSIM_PORTABLE_BUILD:JSON.stringify(buildId)},bundle:true,format:'iife',platform:'browser',target:'chrome100',minify:true,lineLimit:180,charset:'utf8',legalComments:'eof',write:false,metafile:true,plugins:[plugin],
    ...(entry==='main'?{stdin:{contents:"import 'portable:runtime'; import './src/bootstrap.js';",resolveDir:root,sourcefile:'portable-entry.js'}}:{entryPoints:[entry]}),
    banner:{js:`/* SimSim portable ${buildId}. Generated by npm run build:portable. */`},
    ...(entry==='main'?{footer:{js:'/*\n'+license+'*/'}}:{})});
  if(result.warnings.length||Object.values(result.metafile.outputs).some(x=>x.imports.length))throw new Error('Portable build must have no warnings or external imports.');
  const text=result.outputFiles[0].text;
  if(text.includes('import.meta')||/\bimport\s*\(/.test(text))throw new Error('Unbundled module remains in '+name);
  fs.writeFileSync(path.join(out,name),text);
}
let html=fs.readFileSync(path.join(root,'index.html'),'utf8');
html=replaceOnce(html,/src\/bootstrap\.js\?v=[^"\s]+/,'main.js?v='+buildId,'HTML script');
html=replaceOnce(html,/styles\.css\?v=[^"\s]+/,'styles.css?v='+buildId,'HTML CSS');
html=replaceOnce(html,/<a href="environment-check\/check\.html"[^>]*>[^<]*<\/a><a href="docs\/workspace-v3\.md"[^>]*>[^<]*<\/a>/,'<span>保存・読込は上部、分析・配置・地形編集は地図の上部から操作できます。</span>','portable help');
html=html.replace('src・vendor・dataフォルダの配信','main.js・worker.js・analysis-worker.jsの配信');
html=html.replace('<a href="portable/copy.html" target="_blank" rel="noopener">社内持ち込み用ファイル</a>','');
fs.writeFileSync(path.join(out,'index.html'),html);
fs.copyFileSync(path.join(root,'styles.css'),path.join(out,'styles.css'));
const files=['index.html','styles.css','main.js','worker.js','analysis-worker.js'].map(name=>{
  const bytes=fs.readFileSync(path.join(out,name));
  return {name,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')};
});
const copy=fs.readFileSync(path.join(root,'tools/portable-copy.html'),'utf8').replaceAll('__BUILD__',buildId).replace('__FILES__',JSON.stringify(files));
fs.writeFileSync(path.join(out,'copy.html'),copy);
console.log('Portable build: '+buildId+' — index.html, styles.css, main.js, worker.js, analysis-worker.js');
